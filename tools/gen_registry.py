"""data/ui/registry.json -> <build>/generated/{actionids,panelids,settingkeys,workspaceids}.h

Single source of persistent names (docs/ui/naming.md). Source code refers to action, panel, setting and workspace ids
only through these headers; tools/check_literals.py (ctest) fails the build when an id string appears elsewhere.
"""
import argparse
import json
import os
import re
import sys

HEADER = "// generated by tools/gen_registry.py from data/ui/registry.json — do not edit"


def pascal(dotted):
    parts = [p for p in re.split(r"[-_.]", dotted.replace("{n}", "N")) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def unique_idents(items, what):
    idents = [pascal(i) for i in items]
    dup = sorted({i for i in idents if idents.count(i) > 1})
    if dup:
        sys.exit(f"gen_registry: identifier collision in {what}: {dup}")
    return idents


def write_if_changed(path, lines):
    text = "\n".join(lines) + "\n"
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def preamble(extra_includes=()):
    out = [HEADER, "#pragma once", "", "#include <array>", "#include <cstddef>", "#include <cstdint>", "#include <string_view>"]
    out += [f"#include <{inc}>" for inc in extra_includes]
    out.append("")
    return out


def gen_workspaces(reg, out_dir):
    contexts = [c for c in reg["contexts"] if not c.startswith("$")]
    workspaces = []
    for p in reg["panels"]["list"]:
        for w in p.get("workspaces", []):
            if w not in workspaces:
                workspaces.append(w)
    unknown = [w for w in workspaces if w not in contexts]
    if unknown:
        sys.exit(f"gen_registry: panel workspaces not in contexts: {unknown}")
    out = preamble()
    out += ["namespace cc::workspace {", "",
            "/// Shortcut contexts (docs/ui/naming.md section 1 rule 5): focus contexts > workspace contexts > global.",
            "enum class Context : std::uint8_t {"]
    out += [f"    {pascal(c)}," for c in contexts] + ["    Count,", "};"]
    out.append(f"inline constexpr std::array<std::string_view, {len(contexts)}> contextIds{{")
    out += [f"    {cstr(c)}," for c in contexts] + ["};", ""]
    out += ["/// Workspaces = contexts that own panels; the shell holds one Workspace entry per value (PLAN 4-3).",
            "enum class Id : std::uint8_t {"]
    out += [f"    {pascal(w)}," for w in workspaces] + ["    Count,", "};"]
    out.append(f"inline constexpr std::array<std::string_view, {len(workspaces)}> ids{{")
    out += [f"    {cstr(w)}," for w in workspaces] + ["};", "",
            "constexpr std::string_view idOf(Id value)", "{", "    return ids[static_cast<std::size_t>(value)];", "}", "",
            "} // namespace cc::workspace"]
    write_if_changed(os.path.join(out_dir, "workspaceids.h"), out)
    return workspaces


def gen_actions(reg, out_dir):
    actions = reg["actions"]
    ids = [a["id"] for a in actions]
    idents = unique_idents(ids, "actions")
    max_keys = max(len(a.get("keys", [])) for a in actions)
    out = preamble()
    out += ["namespace cc::action {", "",
            "enum class Id : std::uint16_t {"]
    out += [f"    {i}," for i in idents] + ["    Count,", "};", ""]
    out += ["/// One row per registry action. Templated ids keep the literal \"{n}\" and carry their range.",
            "struct Info {",
            "    std::string_view id;",
            "    std::string_view context;",
            "    std::string_view label;          // Korean source text; UI wraps it in translate() (docs/ui/naming.md section 3)",
            "    std::string_view source;         // where the default key comes from (GP8 / own), shown by the keymap editor",
            f"    std::array<std::string_view, {max_keys}> defaultKeys;",
            "    std::uint8_t keyCount;",
            "    bool v1;",
            "    int rangeMin;                    // 0,0 when the id is not a template",
            "    int rangeMax;",
            "};", "",
            f"inline constexpr std::array<Info, {len(actions)}> infos{{{{"]
    for a in actions:
        keys = a.get("keys", [])
        padded = keys + [""] * (max_keys - len(keys))
        rng = a.get("range", [0, 0])
        out.append("    Info{" + ", ".join([cstr(a["id"]), cstr(a["ctx"]), cstr(a.get("label", "")),
                                            cstr(a.get("source", "")),
                                            "{" + ", ".join(cstr(k) for k in padded) + "}",
                                            str(len(keys)), "true" if a.get("v1", False) else "false",
                                            str(rng[0]), str(rng[1])]) + "},")
    out += ["}};", "",
            "constexpr const Info &info(Id value)", "{", "    return infos[static_cast<std::size_t>(value)];", "}",
            "constexpr std::string_view idOf(Id value)", "{", "    return info(value).id;", "}", ""]
    legacy = [e for e in reg.get("legacy", []) if e.get("kind") == "action"]
    out += ["/// Renamed action ids (naming.md section 1 rule 3): loaders read the old name and save the new one.",
            "struct Legacy {", "    std::string_view oldId;", "    std::string_view newId;", "};",
            f"inline constexpr std::array<Legacy, {len(legacy)}> legacy{{{{"]
    out += ["    Legacy{" + cstr(e["old"]) + ", " + cstr(e["new"]) + "}," for e in legacy]
    out += ["}};", "", "} // namespace cc::action"]
    write_if_changed(os.path.join(out_dir, "actionids.h"), out)
    return len(actions)


def gen_panels(reg, out_dir, workspaces):
    panels = reg["panels"]["list"]
    ids = [p["id"] for p in panels]
    idents = unique_idents(ids, "panels")
    out = preamble()
    out += ["namespace cc::panel {", "",
            "enum class Id : std::uint8_t {"]
    out += [f"    {i}," for i in idents] + ["    Count,", "};", ""]
    out += ["/// workspaceMask bit i = cc::workspace::Id value i owns this panel.",
            "struct Info {",
            "    std::string_view id;             // QDockWidget / QToolBar objectName (layout.json key)",
            "    std::string_view label;",
            "    std::uint32_t workspaceMask;",
            "};", "",
            f"inline constexpr std::array<Info, {len(panels)}> infos{{{{"]
    for p in panels:
        mask = 0
        for w in p.get("workspaces", []):
            mask |= 1 << workspaces.index(w)
        out.append("    Info{" + ", ".join([cstr(p["id"]), cstr(p.get("label", "")), f"0x{mask:x}U"]) + "},")
    out += ["}};", "",
            "constexpr const Info &info(Id value)", "{", "    return infos[static_cast<std::size_t>(value)];", "}",
            "constexpr std::string_view idOf(Id value)", "{", "    return info(value).id;", "}", "",
            "} // namespace cc::panel"]
    write_if_changed(os.path.join(out_dir, "panelids.h"), out)
    return len(panels)


def gen_settings(reg, out_dir):
    settings = reg["settings"]["list"]
    ids = [s["id"] for s in settings]
    idents = unique_idents(ids, "settings")
    types = ["bool", "int", "double", "string", "enum", "path", "json"]
    for s in settings:
        if s["type"] not in types:
            sys.exit(f"gen_registry: unknown setting type {s['type']} for {s['id']}")
    out = preamble()
    out += ["namespace cc::setting {", "",
            "enum class Key : std::uint16_t {"]
    out += [f"    {i}," for i in idents] + ["    Count,", "};", "",
            "enum class Type : std::uint8_t { " + ", ".join(pascal(t) for t in types) + " };", "",
            "/// defaultJson / valuesJson are JSON text; the settings loader parses them once at start (docs/ui/naming.md section 5).",
            "struct Info {",
            "    std::string_view key;",
            "    Type type;",
            "    std::string_view page;           // preferences page id, empty for state-only keys",
            "    std::string_view defaultJson;",
            "    std::string_view valuesJson;     // enum: allowed values array, otherwise empty",
            "    int rangeMin;                    // int with \"range\": inclusive bounds, else 0,0",
            "    int rangeMax;",
            "};", "",
            f"inline constexpr std::array<Info, {len(settings)}> infos{{{{"]
    for s in settings:
        rng = s.get("range", [0, 0])
        out.append("    Info{" + ", ".join([cstr(s["id"]), "Type::" + pascal(s["type"]), cstr(s.get("page", "")),
                                            cstr(json.dumps(s.get("default"), ensure_ascii=False, separators=(",", ":"))),
                                            cstr(json.dumps(s["values"], ensure_ascii=False, separators=(",", ":")) if "values" in s else ""),
                                            str(rng[0]), str(rng[1])]) + "},")
    out += ["}};", "",
            "constexpr const Info &info(Key value)", "{", "    return infos[static_cast<std::size_t>(value)];", "}",
            "constexpr std::string_view keyOf(Key value)", "{", "    return info(value).key;", "}", "",
            "} // namespace cc::setting"]
    write_if_changed(os.path.join(out_dir, "settingkeys.h"), out)
    return len(settings)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    with open(args.registry, encoding="utf-8") as f:
        reg = json.load(f)
    os.makedirs(args.out, exist_ok=True)
    workspaces = gen_workspaces(reg, args.out)
    n_actions = gen_actions(reg, args.out)
    n_panels = gen_panels(reg, args.out, workspaces)
    n_settings = gen_settings(reg, args.out)
    print(f"gen_registry: {n_actions} actions, {n_panels} panels, {n_settings} settings, {len(workspaces)} workspaces -> {args.out}")


if __name__ == "__main__":
    main()
