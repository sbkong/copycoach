"""data/ui/theme-dark.json + theme-light.json -> <build>/generated/tokens.h

Emits enums and name tables for every token *name* (colors, shape, spacing, typography). Values are not compiled in:
the app loads the theme JSON at start so the theme can switch at runtime (PLAN 4-3). The generator fails when the
two theme files disagree on a key set, so a token added to one theme only is a build error (docs/ui/naming.md section 6).
"""
import argparse
import json
import os
import re
import sys


def pascal(kebab):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_.]", kebab) if part)


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def keys_of(theme, section):
    return [k for k in theme.get(section, {}) if not k.startswith("$")]


def check_same(dark, light, section):
    d, l = keys_of(dark, section), keys_of(light, section)
    if d != l:
        only_d = sorted(set(d) - set(l))
        only_l = sorted(set(l) - set(d))
        sys.exit(f"gen_tokens: section '{section}' differs between themes: dark-only {only_d}, light-only {only_l}")
    return d


def emit_enum(out, enum_name, names, doc):
    idents = [pascal(n) for n in names]
    dup = {i for i in idents if idents.count(i) > 1}
    if dup:
        sys.exit(f"gen_tokens: identifier collision in {enum_name}: {sorted(dup)}")
    out.append(f"/// {doc}")
    out.append(f"enum class {enum_name} : std::uint16_t {{")
    for i in idents:
        out.append(f"    {i},")
    out.append("    Count,")
    out.append("};")
    out.append(f"inline constexpr std::array<std::string_view, {len(names)}> {enum_name[:1].lower() + enum_name[1:]}Names{{")
    for n in names:
        out.append(f'    "{n}",')
    out.append("};")
    out.append(f"constexpr std::string_view name({enum_name} value)")
    out.append("{")
    out.append(f"    return {enum_name[:1].lower() + enum_name[1:]}Names[static_cast<std::size_t>(value)];")
    out.append("}")
    out.append("")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dark", required=True)
    ap.add_argument("--light", required=True)
    ap.add_argument("--out", required=True, help="output directory (generated/)")
    args = ap.parse_args()
    dark, light = load(args.dark), load(args.light)

    colors = check_same(dark, light, "semantic") + check_same(dark, light, "component")
    shape = check_same(dark, light, "shape")
    spacing = check_same(dark, light, "spacing")
    typography = check_same(dark, light, "typography")
    fonts = [k for k in check_same(dark, light, "font")]

    rel = lambda p: os.path.basename(p)
    out = [
        f"// generated by tools/gen_tokens.py from data/ui/{rel(args.dark)} and {rel(args.light)} — do not edit",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace cc::theme {",
        "",
    ]
    emit_enum(out, "Token", colors, "Color tokens: semantic then component tier (Spectrum naming, see docs/ui/naming.md section 2).")
    emit_enum(out, "Shape", shape, "Shape values (radii, island gap); light theme may hold null for island entries.")
    emit_enum(out, "Spacing", spacing, "Spacing scale in epx (Fluent 2).")
    emit_enum(out, "TypeStyle", typography, "Type ramp entries: size, line-height, weight.")
    emit_enum(out, "FontKey", fonts, "Font stack keys (font-family lists and the numbers feature).")
    out.append("} // namespace cc::theme")
    out.append("")

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "tokens.h")
    text = "\n".join(out)
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"gen_tokens: {len(colors)} color tokens, {len(shape)} shape, {len(spacing)} spacing, {len(typography)} type styles -> {path}")


if __name__ == "__main__":
    main()
